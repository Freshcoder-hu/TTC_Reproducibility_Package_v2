def _trec_decision(nums):
    return (
        "**The frozen 15 s is kept, and the sweep is why.**\n\n"
        "1. **The requested 12 s arm does not exist.**  `Proposed.__init__` "
        "asserts `t_rec > t_pre`, and the Stage-3 acceptance gate `T_REC > "
        "T_PRE` is part of the frozen tuple, so a 12 s arm cannot be built; the "
        "sweep's low arm is the admissible **12.5 s**.\n"
        "2. **Rule R3, re-derived on the windows that actually closed, returns "
        "exactly the frozen value.**  On V2S3 at 220 m, 10 episodes closed "
        "normally, median duration **3.00 s** — the `h` floor — so "
        "`T_REC = 12 + max(3, 3) = 15.0 s`.  Stage 4's worry (\"the median is far "
        "above the V1 value\") came from counting the *preempted* 1.0 s window "
        "and the 9.5 s one; on the ten closed episodes the distribution is 1.0, "
        "1.0, 2.0, 2.1, 2.9, 3.1, 3.3, 3.6, 3.8, 9.5 s, whose median is the "
        "floor.  The 9.5 s outlier is a single episode, not the typical one.\n"
        "3. **The whole admissible range is inactive on this geometry.**  "
        "12.5 / 15 / 18 s produce **bit-identical** runs on both scenes (every "
        "outcome and window column equal to the last digit), because the "
        "RECOVER → NORMAL exit is governed by the geometric recovery condition "
        "(ρ ≥ 0.88, |lat| ≤ 3.0 m) once the TTC clause is satisfied by the "
        "clearance, not by a timer.  The median re-entry delay (3.0 s) equals "
        "the median window duration, i.e. the window is spent restoring the "
        "formation, not waiting.\n"
        "4. **Therefore 15 s neither truncates a legitimate re-entry nor delays "
        "one** on these scenes, and it is retained.  The honest statement is "
        "that the value is *re-validated* (the rule reproduces it) and "
        "*inactive* (the range does not matter here) — not that it was tuned.\n")


